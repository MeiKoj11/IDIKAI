/*
  spanish-sentence-test-app.js
  ------------------------------
  spanish-sentence-test.html — "sentence mode" Conjugation Test: same
  design-your-own/random config screen as the quick Conjugation Test
  (spanish-conjugation-test-app.js), but each question is a full,
  natural sentence generated by the AI (not a local template) — see
  server.js's GENERATE_CONJUGATION_SENTENCE_PROMPT — and grading is
  verb-strict/everything-else-lenient, also via the AI (see
  CHECK_CONJUGATION_SENTENCE_PROMPT). Any word in the displayed sentence
  can be clicked to look it up and add it straight to the Vocab Bank,
  reusing the same lookup-panel pattern Reading uses.
*/

