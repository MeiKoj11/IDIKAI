// Every person can come up; yo/tú just show up a bit more often.
const TEST_PERSON_WEIGHTS = { yo: 0.24, tu: 0.24, el: 0.15, nosotros: 0.13, vosotros: 0.11, ellos: 0.13 };
const TEST_IMPERATIVE_PERSON_WEIGHTS = { tu: 0.32, el: 0.22, nosotros: 0.16, vosotros: 0.12, ellos: 0.18 };

function weightedPick(weights) {
  const entries = Object.entries(weights);
  const total = entries.reduce((sum, [, w]) => sum + w, 0);
  let r = Math.random() * total;
  for (const [key, w] of entries) {
    r -= w;
    if (r <= 0) return key;
  }
  return entries[entries.length - 1][0];
}

// 70% regular / 30% irregular — only used by the one-click Random test.
function pickWeightedRandomVerb(verbs) {
  const irregular = verbs.filter((v) => v.irregular);
  const regular = verbs.filter((v) => !v.irregular);
  const pool = Math.random() < 0.3 && irregular.length ? irregular : regular.length ? regular : verbs;
  return pool[Math.floor(Math.random() * pool.length)];
}

function pickTestPerson(tense, persons, weighted) {
  const validPersons = persons.filter((p) => personsForTense(tense).includes(p));
  if (!validPersons.length) return null;
  if (!weighted) return validPersons[Math.floor(Math.random() * validPersons.length)];
  const fullWeights = SpanishConjugator.IMPERATIVE_TENSE_KEYS.includes(tense) ? TEST_IMPERATIVE_PERSON_WEIGHTS : TEST_PERSON_WEIGHTS;
  const weights = {};
  validPersons.forEach((p) => {
    if (fullWeights[p]) weights[p] = fullWeights[p];
  });
  return Object.keys(weights).length ? weightedPick(weights) : validPersons[Math.floor(Math.random() * validPersons.length)];
}

// ---------------------------------------------------------------------
// Session / question generation — this is the part that differs from
// the quick test: each question needs an AI round-trip (there's no
// local sentence-generation engine), so building a question is async
// and can fail/be retried.
// ---------------------------------------------------------------------

let sentenceTestSession = null; // { config, correct, total, current, recentSentences }

// Picks WHICH verb/tense/person/direction to ask about next — cheap and
// synchronous; the actual sentence text comes from the AI afterwards.
function pickQuestionSpec(config, guard) {
  const safeGuard = guard || 0;
  if (safeGuard > 40) return null;
  const tense = config.tenses[Math.floor(Math.random() * config.tenses.length)];
  const person = pickTestPerson(tense, config.persons, config.weighted);
  if (!person) return pickQuestionSpec(config, safeGuard + 1);
  const verb = config.weighted ? pickWeightedRandomVerb(config.verbs) : config.verbs[Math.floor(Math.random() * config.verbs.length)];
  const direction = config.direction === "mixed" ? (Math.random() < 0.5 ? "enToTl" : "tlToEn") : config.direction;
  return { tense, person, verb, direction };
}

function startTensesTestWithConfig(config) {
  if (!config.verbs.length || !config.persons.length || !config.tenses.length) return;
  sentenceTestSession = { config, correct: 0, total: 0, current: null, recentSentences: [] };
  document.getElementById("tenses-test-setup").hidden = true;
  document.getElementById("tenses-test-quiz").hidden = false;
  document.getElementById("lookup-panel").hidden = true;
  nextSentenceTestQuestion();
}

function startTensesTest() {
  const verbs = selectedTestVerbs();
  const persons = selectedTestPersons();
  const tenses = selectedTestTenses();
  const direction = selectedTestDirection();
  startTensesTestWithConfig({ verbs, persons, tenses, direction, weighted: false });
}

function startRandomTensesTest() {
  startTensesTestWithConfig({
    verbs: buildSpanishVerbPool(),
    persons: SpanishConjugator.PERSON_KEYS.slice(),
    tenses: SpanishConjugator.ALL_TENSE_KEYS.slice(),
    direction: "enToTl",
    weighted: true,
  });
}

async function nextSentenceTestQuestion() {
  if (!sentenceTestSession) return;
  const session = sentenceTestSession;
  const spec = pickQuestionSpec(session.config);

  const loadingEl = document.getElementById("sentence-test-loading");
  const promptLabelEl = document.getElementById("sentence-test-prompt-label");
  const promptEl = document.getElementById("sentence-test-prompt");
  const revealBtn = document.getElementById("tenses-test-show-infinitive-btn");
  const revealEl = document.getElementById("tenses-test-infinitive-reveal");
  const input = document.getElementById("tenses-test-input");
  const checkBtn = document.getElementById("tenses-test-check-btn");
  const nextBtn = document.getElementById("tenses-test-next-btn");
  const feedback = document.getElementById("tenses-test-feedback");

  document.getElementById("lookup-panel").hidden = true;

  if (!spec) {
    promptLabelEl.hidden = true;
    promptEl.textContent = "Couldn't build a question from this selection — try picking more verbs/persons/tenses.";
    revealBtn.hidden = true;
    revealEl.hidden = true;
    checkBtn.hidden = true;
    nextBtn.hidden = true;
    return;
  }

  loadingEl.hidden = false;
  promptLabelEl.hidden = true;
  promptEl.textContent = "";
  revealBtn.hidden = true;
  revealEl.hidden = true;
  feedback.hidden = true;
  checkBtn.hidden = true;
  nextBtn.hidden = true;
  input.value = "";
  input.disabled = true;

  const tenseLabel = SpanishConjugator.ALL_TENSE_LABELS[spec.tense] || spec.tense;
  const personLabel = SpanishConjugator.PERSON_LABELS[spec.person] || spec.person;
  const result = await Translate.generateConjugationSentence(
    "es",
    spec.verb.infinitive,
    spec.verb.english,
    tenseLabel,
    personLabel,
    session.recentSentences
  );

  // The learner may have hit "Change setup" while this call was in
  // flight — bail rather than rendering into a session that's gone.
  if (sentenceTestSession !== session) return;

  loadingEl.hidden = true;

  if (result.error || !result.englishSentence || !result.targetSentence) {
    promptEl.textContent = `Couldn't generate a sentence (${result.error || "unexpected response"}) — try Next again.`;
    nextBtn.hidden = false;
    return;
  }

  session.current = Object.assign({}, spec, result);
  session.recentSentences.push(result.englishSentence, result.targetSentence);
  if (session.recentSentences.length > 12) {
    session.recentSentences.splice(0, session.recentSentences.length - 12);
  }

  renderSentenceTestQuestion();
}

function renderSentenceTestQuestion() {
  const session = sentenceTestSession;
  if (!session || !session.current) return;
  const { direction, englishSentence, targetSentence } = session.current;
  const promptLang = direction === "tlToEn" ? "es" : "en";
  const promptSentence = promptLang === "es" ? targetSentence : englishSentence;

  const promptLabelEl = document.getElementById("sentence-test-prompt-label");
  promptLabelEl.hidden = false;
  promptLabelEl.textContent = promptLang === "es" ? "Translate to English:" : "Translate to Spanish:";

  renderClickableSentence(document.getElementById("sentence-test-prompt"), promptSentence, promptLang);

  const input = document.getElementById("tenses-test-input");
  input.value = "";
  input.disabled = false;
  input.placeholder = promptLang === "es" ? "Type it in English…" : "Type it in Spanish…";

  document.getElementById("tenses-test-show-infinitive-btn").hidden = false;
  document.getElementById("tenses-test-infinitive-reveal").hidden = true;
  document.getElementById("tenses-test-feedback").hidden = true;
  document.getElementById("tenses-test-check-btn").hidden = false;
  document.getElementById("tenses-test-next-btn").hidden = true;
  updateSentenceTestScore();
  input.focus();
}

// Splits on whitespace (keeping it, like reading-app.js's tokenizer) and
// strips leading/trailing punctuation per token so "clave." looks up
// "clave" — \p{L} is any Unicode letter, so accented letters count.
function tokenizeSentence(text) {
  return (text || "").split(/(\s+)/);
}
function stripPunctuation(token) {
  return token.replace(/^[^\p{L}]+|[^\p{L}]+$/gu, "");
}

function renderClickableSentence(container, sentence, lang) {
  container.innerHTML = "";
  tokenizeSentence(sentence).forEach((token) => {
    const core = stripPunctuation(token);
    if (!token || !core) {
      container.appendChild(document.createTextNode(token));
      return;
    }
    const span = document.createElement("span");
    span.className = "clickable-word";
    span.textContent = token;
    span.dataset.word = core;
    span.addEventListener("click", () => handleSentenceWordClick(span, core, lang));
    container.appendChild(span);
  });
}

function showInfinitiveReveal() {
  if (!sentenceTestSession || !sentenceTestSession.current) return;
  const { verb } = sentenceTestSession.current;
  const revealEl = document.getElementById("tenses-test-infinitive-reveal");
  revealEl.textContent = `${verb.infinitive} (${verb.english})`;
  revealEl.hidden = false;
}

function updateSentenceTestScore() {
  const score = document.getElementById("tenses-test-score");
  if (score && sentenceTestSession) score.textContent = `Score: ${sentenceTestSession.correct} / ${sentenceTestSession.total}`;
}

// Verb-strict, everything-else-lenient — the AI does the actual
// judgment (see CHECK_CONJUGATION_SENTENCE_PROMPT in server.js); this
// just picks which side of the sentence pair to grade against based on
// which language the learner was asked to answer in.
async function checkSentenceTestAnswer() {
  if (!sentenceTestSession || !sentenceTestSession.current) return;
  const input = document.getElementById("tenses-test-input");
  const typed = input.value.trim();
  if (!typed) return;

  const session = sentenceTestSession;
  const { direction, englishSentence, targetSentence, verbFormEnglish, verbFormTarget } = session.current;
  const answerLanguage = direction === "tlToEn" ? "en" : "es";
  const referenceSentence = answerLanguage === "es" ? targetSentence : englishSentence;
  const expectedVerbForm = answerLanguage === "es" ? verbFormTarget : verbFormEnglish;

  const checkBtn = document.getElementById("tenses-test-check-btn");
  const checkingEl = document.getElementById("sentence-test-checking");
  input.disabled = true;
  checkBtn.hidden = true;
  checkingEl.hidden = false;

  const result = await Translate.checkConjugationSentence(answerLanguage, referenceSentence, expectedVerbForm, typed);

  if (sentenceTestSession !== session) return;
  checkingEl.hidden = true;

  const feedback = document.getElementById("tenses-test-feedback");
  feedback.innerHTML = "";
  feedback.hidden = false;

  if (result.error || result.verbCorrect === null) {
    feedback.textContent = "Couldn't check that answer — try again.";
    feedback.className = "card-practice-answer card-practice-wrong";
    input.disabled = false;
    checkBtn.hidden = false;
    return;
  }

  session.total += 1;
  if (result.verbCorrect) session.correct += 1;
  updateSentenceTestScore();

  const verdict = document.createElement("strong");
  verdict.textContent = result.verbCorrect ? "Correct verb!" : "Not quite — the verb wasn't right.";
  feedback.appendChild(verdict);

  if (result.corrected && result.corrected.trim() && result.corrected.trim() !== typed) {
    const correctedLine = document.createElement("div");
    correctedLine.textContent = result.corrected.trim();
    feedback.appendChild(correctedLine);
  }
  if (result.note) {
    const noteLine = document.createElement("div");
    noteLine.className = "hint";
    noteLine.textContent = result.note;
    feedback.appendChild(noteLine);
  }
  feedback.className = result.verbCorrect ? "card-practice-answer" : "card-practice-answer card-practice-wrong";

  document.getElementById("tenses-test-next-btn").hidden = false;
}

function backToSetup() {
  document.getElementById("tenses-test-setup").hidden = false;
  document.getElementById("tenses-test-quiz").hidden = true;
  document.getElementById("lookup-panel").hidden = true;
  sentenceTestSession = null;
}

// ---------------------------------------------------------------------
// Word-click lookup + Add-to-Vocab — mirrors reading-app.js's
// .lookup-panel pattern. Since a clicked word can be on EITHER side of
// the sentence pair (English prompt word she doesn't know the Spanish
// for, or a Spanish word she doesn't recognize), the lookup direction
// and which field becomes "targetLang" vs "english" when saving both
// depend on which language the clicked word was actually in.
// ---------------------------------------------------------------------

const NEW_THEME_VALUE = "__new_theme__";
let selectedSentenceWord = null;

function renderSentenceThemeOptions(selectId) {
  const select = document.getElementById("add-to-theme-select");
  if (!select) return;
  select.innerHTML = "";

  const themes = Storage.getThemes().filter((t) => t.language === "es");
  themes.forEach((theme) => {
    const opt = document.createElement("option");
    opt.value = theme.id;
    opt.textContent = theme.name;
    select.appendChild(opt);
  });

  const newOpt = document.createElement("option");
  newOpt.value = NEW_THEME_VALUE;
  newOpt.textContent = "+ Create new theme…";
  newOpt.dataset.immersionKey = "createNewThemeOption";
  select.appendChild(newOpt);

  if (selectId) {
    select.value = selectId;
  } else if (themes.length === 0) {
    select.value = NEW_THEME_VALUE;
  }
}

function createSentenceLookupTheme() {
  const name = prompt("Name for the new theme:");
  const existingThemes = Storage.getThemes().filter((t) => t.language === "es");
  if (!name || !name.trim()) {
    renderSentenceThemeOptions(existingThemes.length ? existingThemes[0].id : null);
    return;
  }
  const theme = Storage.addTheme(name.trim(), "es");
  renderSentenceThemeOptions(theme.id);
}

function handleSentenceThemeSelectChange(e) {
  if (e.target.value !== NEW_THEME_VALUE) return;
  createSentenceLookupTheme();
}

function handleAddLookedUpSentenceWord() {
  const select = document.getElementById("add-to-theme-select");
  let themeId = select.value;
  if (!themeId || themeId === NEW_THEME_VALUE) {
    const name = prompt("Name for the new theme:");
    if (!name || !name.trim()) return;
    const theme = Storage.addTheme(name.trim(), "es");
    renderSentenceThemeOptions(theme.id);
    themeId = theme.id;
  }

  const addBtn = document.getElementById("add-looked-up-word");
  const english = addBtn.dataset.english;
  const targetLang = addBtn.dataset.targetLang;
  const saved = Storage.addWordIfNotDuplicate(themeId, {
    english,
    targetLang,
    furigana: "",
    notes: "",
  });

  const resultEl = document.getElementById("lookup-result");
  if (saved) {
    resultEl.textContent = `${english} — added.`;
    addBtn.hidden = true;
  } else {
    resultEl.textContent = `${english} — already in your deck.`;
  }
}

// `lang` is whichever language the clicked word actually appeared in
// ("es" or "en") — the sentence shown as the prompt can be either,
// depending on direction.
async function handleSentenceWordClick(span, word, lang) {
  document.querySelectorAll(".clickable-word.selected").forEach((el) => el.classList.remove("selected"));
  span.classList.add("selected");
  selectedSentenceWord = word;

  const panel = document.getElementById("lookup-panel");
  panel.hidden = false;
  document.getElementById("lookup-word").textContent = word;
  const resultEl = document.getElementById("lookup-result");
  resultEl.textContent = "Looking up…";
  document.getElementById("lookup-grammar").textContent = "";
  document.getElementById("add-looked-up-word").hidden = true;
  renderSentenceThemeOptions();

  const toLang = lang === "en" ? "es" : "en";
  const result = await Translate.lookupTranslation(word, lang, toLang);
  if (selectedSentenceWord !== word) return; // a different word was clicked meanwhile
  if (!result || !result.translation) {
    resultEl.textContent = "No translation found.";
    return;
  }

  resultEl.textContent = result.translation;
  const addBtn = document.getElementById("add-looked-up-word");
  addBtn.hidden = false;
  if (lang === "es") {
    addBtn.dataset.targetLang = word;
    addBtn.dataset.english = result.translation;
  } else {
    addBtn.dataset.targetLang = result.translation;
    addBtn.dataset.english = word;
  }
}

